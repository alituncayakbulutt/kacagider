create table if not exists public.trust_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  account_type text not null default 'seller' check (account_type in ('seller','dealer')),
  display_name text,
  phone_verified boolean not null default false,
  identity_verified boolean not null default false,
  dealer_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.trust_events (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  points smallint not null check (points between -50 and 50),
  reference_id text,
  note text,
  created_at timestamptz not null default now()
);

create unique index if not exists trust_events_unique_reference_idx
  on public.trust_events(actor_id,event_type,reference_id)
  where reference_id is not null;

create index if not exists trust_events_actor_idx
  on public.trust_events(actor_id,created_at desc);

alter table public.trust_profiles enable row level security;
alter table public.trust_events enable row level security;

-- Kullanıcı yalnızca kendi profil satırını okuyabilir. Dışarıya açık veri RPC ile döner.
drop policy if exists trust_profiles_select_own on public.trust_profiles;
create policy trust_profiles_select_own
  on public.trust_profiles for select
  to authenticated
  using (auth.uid() = user_id);

