$$;

create or replace function public.admin_set_listing_status(
  p_listing_id uuid,
  p_status text
)
returns public.listings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old public.listings;
  v_new public.listings;
begin
  if not public.is_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;
  if p_status not in ('draft', 'published', 'sold', 'archived') then
    raise exception 'Geçersiz ilan durumu.' using errcode = '22023';
  end if;

  select * into v_old from public.listings where id = p_listing_id;
  if not found then
    raise exception 'İlan bulunamadı.' using errcode = 'P0002';
  end if;

  update public.listings
  set status = p_status,
      published_at = case when p_status = 'published' and published_at is null then now() else published_at end,
      updated_at = now()
  where id = p_listing_id
  returning * into v_new;

  insert into public.admin_audit_log (admin_user_id, action, target_type, target_id, metadata)
  values ((select auth.uid()), 'listing_status_changed', 'listing', p_listing_id,
          jsonb_build_object('old_status', v_old.status, 'new_status', v_new.status));

  return v_new;
end;
$$;

create or replace function public.admin_delete_listing(p_listing_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_listing public.listings;
begin
  if not public.is_admin() then
    raise exception 'Yönetici yetkisi gerekli.' using errcode = '42501';
  end if;

  select * into v_listing from public.listings where id = p_listing_id;
  if not found then
    raise exception 'İlan bulunamadı.' using errcode = 'P0002';
  end if;

  delete from public.listings where id = p_listing_id;

  insert into public.admin_audit_log (admin_user_id, action, target_type, target_id, metadata)
  values ((select auth.uid()), 'listing_deleted', 'listing', p_listing_id,
          jsonb_build_object('brand', v_listing.brand, 'model', v_listing.model,
                             'seller_price', v_listing.seller_price, 'status', v_listing.status));

  return true;
end;
$$;

