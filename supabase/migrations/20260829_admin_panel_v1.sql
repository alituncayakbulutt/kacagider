create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin', 'super_admin')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

alter table public.admin_users enable row level security;
revoke all on table public.admin_users from anon, authenticated;
grant select on table public.admin_users to authenticated;

do $storage$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'admin_users'
      and policyname = 'admin_users_self_select'
  ) then
    execute 'create policy admin_users_self_select on public.admin_users for select to authenticated using ((select auth.uid()) = user_id)';
  end if;
end $storage$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
      and active = true
      and role in ('admin', 'super_admin')
  );
$$;

revoke all on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='listings' and policyname='listings_admin_select') then
    execute 'create policy listings_admin_select on public.listings for select to authenticated using ((select public.is_admin()))';
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='listing_photos' and policyname='listing_photos_admin_select') then
    execute 'create policy listing_photos_admin_select on public.listing_photos for select to authenticated using ((select public.is_admin()))';
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='profiles_admin_select') then
    execute 'create policy profiles_admin_select on public.profiles for select to authenticated using ((select public.is_admin()))';
  end if;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and policyname = 'listing_images_admin_delete'
  ) then
    execute $sql$create policy listing_images_admin_delete on storage.objects
      for delete to authenticated
      using (bucket_id = 'listing-images' and (select public.is_admin()))$sql$;
  end if;
end $$;

